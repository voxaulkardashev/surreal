export type SkyBody =
  | 'none'
  | 'moon'
  | 'planet'
  | 'sun'
  | 'star'
  | 'binary'
  | 'nebula'
  | 'galaxy'
  | 'blackhole'
  | 'cluster'
  | 'void'
  | 'wall';

export type Horizon = 'none' | 'hills' | 'ridge' | 'trees' | 'shrine' | 'sea' | 'city';

export interface Sky {
  /** Vertical gradient: zenith, middle, horizon. */
  gradient: [string, string, string];
  /** Colour of the glow sitting on the horizon line. */
  glow: string;
  /** Colour of the feature body and of UI accents on this page. */
  accent: string;
  /** Star density multiplier, 0 (empty) to 2 (crowded). */
  stars: number;
  /** Long-exposure star trails instead of points. */
  trails?: boolean;
  /** Amount of nebular haze, 0 to 1. */
  haze: number;
  body: SkyBody;
  /** Relative size of the feature body. */
  bodyScale?: number;
  horizon: Horizon;
}

export type Mood = 'calm' | 'wonder' | 'vast' | 'dark' | 'warm' | 'crystal' | 'ancient';

export interface Destination {
  slug: string;
  /** What goes in the destination field, exactly as the poster would print it. */
  name: string;
  /** Optional qualifier printed under the name. */
  designation?: string;
  category: Category;
  /** Straight-line distance from Earth, in kilometres. */
  distanceKm: number;
  /** How that distance was pinned down — closest approach, mean, comoving… */
  basis: string;
  /** One line, printed under the card. */
  blurb: string;
  /** A longer field note for the journey section. */
  note: string;
  /** A fact worth the trip. */
  fact: string;
  sky: Sky;
  mood: Mood;
}

