/** Every catalog entry keyed by slug, Earth included. */
export const BY_SLUG: Record<string, Destination> = Object.fromEntries(
  [EARTH, ...DESTINATIONS].map((d) => [d.slug, d]),
);

export const getDestination = (slug: string): Destination | undefined => BY_SLUG[slug];

export const destinationsIn = (category: Category): Destination[] =>
  DESTINATIONS.filter((d) => d.category === category);

/** Catalog order is roughly by distance; this makes that explicit. */
export const BY_DISTANCE: Destination[] = [...DESTINATIONS].sort((a, b) => a.distanceKm - b.distanceKm);

export function neighbours(slug: string): { previous: Destination; next: Destination } {
  const index = Math.max(0, BY_DISTANCE.findIndex((d) => d.slug === slug));
  const size = BY_DISTANCE.length;
  return {
    previous: BY_DISTANCE[(index - 1 + size) % size],
    next: BY_DISTANCE[(index + 1) % size],
  };
}

/**
 * Distance between two catalog entries.
 *
 * Everything is catalogued as a radial distance from Earth, so this is a
 * first-order separation, exact when the origin is Earth and honest-ish
 * otherwise. The site says as much wherever a non-Earth origin is picked.
 */
export function separation(origin: Destination, destination: Destination): number {
  return Math.abs(destination.distanceKm - origin.distanceKm);
}

/** Origins worth offering. Anything further out stops being a journey. */
export const ORIGIN_SLUGS = ['earth', 'moon', 'mars', 'voyager-1', 'oort-cloud'];

export const ORIGINS: Destination[] = ORIGIN_SLUGS.map((slug) => BY_SLUG[slug]).filter(Boolean);
